// Copies the curated template fonts from @fontsource into dist/fonts/ and writes one CSS file per
// family (dist/fonts/<slug>.css) with the package's own unicode-range per subset, so a browser
// source only downloads the faces and subsets a template actually renders.
// Runs after `vite build` (which empties dist). `--dry-run` prints the plan without writing.
import { copyFileSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

/** Slugs = @fontsource package names. Mirrors FONTS in src/fonts.ts (and TEMPLATE_FONTS in model.rs). */
export const SLUGS = [
  "barlow",
  "barlow-condensed",
  "oswald",
  "montserrat",
  "ibm-plex-sans",
  "ibm-plex-sans-condensed",
  "source-serif-4",
  "roboto-mono",
  "ibm-plex-mono",
  "space-grotesk",
  "manrope",
  "archivo",
  "playfair-display",
  "jost",
  "instrument-sans",
  "plus-jakarta-sans",
  "outfit",
];
/** The default weights. 500 is left out to stay near the budget: a 500 request falls back to 400. */
export const WEIGHTS = [400, 600, 700];
/** Families whose styles need other weights than WEIGHTS (only what the style library uses). */
export const FAMILY_WEIGHTS = {
  "space-grotesk": [400, 500, 600, 700], // Frame
  "ibm-plex-sans": [400, 500, 600, 700], // Corporate
  manrope: [400, 500, 600],
  archivo: [400, 600, 700, 800],
  jost: [400, 500, 600],
  "instrument-sans": [400, 500, 600],
  outfit: [400, 500, 600, 700],
};
/** Italic weights per family (none otherwise): the serif styles (Elegant, Editorial). */
export const FAMILY_ITALICS = { "playfair-display": [400, 600], "source-serif-4": [400] };
/** The weights shipped for a family. */
export const weightsOf = (slug) => FAMILY_WEIGHTS[slug] || WEIGHTS;
/** The italic weights shipped for a family. */
export const italicsOf = (slug) => FAMILY_ITALICS[slug] || [];
export const SUBSETS = ["latin-ext", "latin"];

/** Parses `/* <id> *\/ @font-face { ... }` blocks of a @fontsource CSS file into id → props. */
function blocks(css) {
  const out = new Map();
  const re = /\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g;
  for (let m; (m = re.exec(css)); ) {
    const props = {};
    for (const d of m[2].split(";")) {
      const i = d.indexOf(":");
      if (i > 0) props[d.slice(0, i).trim()] = d.slice(i + 1).trim();
    }
    out.set(m[1], props);
  }
  return out;
}

/**
 * Plans every family: the CSS text and the woff2 files to copy. Pure apart from reading the
 * packages, so tests can call it directly.
 * @returns {{ slug: string, css: string, files: { from: string, name: string, bytes: number }[] }[]}
 */
export function plan(modules = join(here, "..", "node_modules", "@fontsource")) {
  return SLUGS.map((slug) => {
    const pkg = join(modules, slug);
    const faces = [];
    const files = [];
    const styles = [...weightsOf(slug).map((w) => [w, "normal"]), ...italicsOf(slug).map((w) => [w, "italic"])];
    for (const [w, style] of styles) {
      const file = style === "normal" ? `${w}.css` : `${w}-italic.css`;
      let css;
      try {
        css = readFileSync(join(pkg, file), "utf8");
      } catch {
        if (style === "italic") throw new Error(`fonts: @fontsource/${slug} ships no ${file}`);
        continue; // weight not shipped by this family
      }
      const b = blocks(css);
      for (const sub of SUBSETS) {
        const id = `${slug}-${sub}-${w}-${style}`;
        const p = b.get(id);
        if (!p || !p["unicode-range"]) throw new Error(`fonts: no "${id}" block in @fontsource/${slug}/${file}`);
        const name = `${id}.woff2`;
        const from = join(pkg, "files", name);
        files.push({ from, name, bytes: statSync(from).size });
        faces.push(
          `/* ${id} */\n@font-face {\n  font-family: ${p["font-family"]};\n  font-style: ${style};\n  font-display: swap;\n` +
            `  font-weight: ${w};\n  src: url(./${slug}/${name}) format('woff2');\n  unicode-range: ${p["unicode-range"]};\n}\n`,
        );
      }
    }
    if (!faces.length) throw new Error(`fonts: @fontsource/${slug} has none of the weights ${weightsOf(slug)}`);
    return { slug, css: `/* ${slug}: OFL, from @fontsource/${slug}. Generated by scripts/fonts.mjs. */\n` + faces.join("\n"), files };
  });
}

export function run(out = join(here, "..", "dist", "fonts"), dryRun = false) {
  const families = plan();
  let total = 0;
  for (const f of families) {
    const bytes = f.files.reduce((n, x) => n + x.bytes, 0) + f.css.length;
    total += bytes;
    console.log(`  ${f.slug.padEnd(24)} ${String(f.files.length).padStart(2)} files ${(bytes / 1024).toFixed(1).padStart(7)} KB`);
    if (dryRun) continue;
    mkdirSync(join(out, f.slug), { recursive: true });
    for (const x of f.files) copyFileSync(x.from, join(out, f.slug, x.name));
    writeFileSync(join(out, `${f.slug}.css`), f.css);
  }
  console.log(`fonts: ${families.length} families, weights ${WEIGHTS.join("/")} (+ per family: ${Object.entries(FAMILY_WEIGHTS).map(([f, w]) => `${f} ${w.join("/")}`).join(", ")}; italic: ${Object.entries(FAMILY_ITALICS).map(([f, w]) => `${f} ${w.join("/")}`).join(", ")}),${(total / 1024).toFixed(1)} KB total${dryRun ? " (dry run)" : ` → ${out}`}`);
  return total;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) run(undefined, process.argv.includes("--dry-run"));
